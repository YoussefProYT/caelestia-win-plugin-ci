#!/usr/bin/env python3
"""Add Windows DLL export/import macros to Caelestia's plugin headers (CI-time, not a patch).

Usage: python tools/gen_exports.py <path-to-caelestia-checkout> [report-file]

What it does (Windows-only effect, Linux build unchanged because the macros expand to nothing there):
 1. Finds each qml_module(caelestia-NAME ...) in plugin/src/Caelestia/**/CMakeLists.txt and maps its directory to NAME.
 2. Writes plugin/include/caelestia_export.h with CAELESTIA_<NAME>_API macros
    (dllexport while compiling that library, dllimport everywhere else).
 3. Inserts the macro into top-level `class X` / `struct X` definitions in that directory's headers.
    Skipped: forward declarations, enum class, templates, indented (nested) types, already-marked types.
 4. Adds include_directories(include) before the first add_subdirectory() and appends a block to
    plugin/CMakeLists.txt that defines CAELESTIA_BUILD_<NAME> for every shared caelestia-* target.
Prints a report; exits non-zero if it could not map any library.
"""
import re, sys, pathlib

root = pathlib.Path(sys.argv[1]).resolve()
plugin = root / "plugin"
src = plugin / "src" / "Caelestia"
if not src.is_dir():
    sys.exit(f"not found: {src}")

QML_MODULE = re.compile(r"qml_module\(\s*(caelestia-[A-Za-z0-9_-]+)")

def lib_key(target: str) -> str:
    return re.sub(r"[^A-Z0-9]", "_", target[len("caelestia-"):].upper())

# directory -> target name
dir_to_target = {}
for cm in sorted(src.rglob("CMakeLists.txt")):
    m = QML_MODULE.search(cm.read_text(encoding="utf-8", errors="replace"))
    if m:
        dir_to_target[cm.parent] = m.group(1)
if not dir_to_target:
    sys.exit("no qml_module(caelestia-...) found")

keys = sorted({lib_key(t) for t in dir_to_target.values()})

# --- header ---
inc = plugin / "include"
inc.mkdir(exist_ok=True)
lines = ["#pragma once", "", "// Generated by tools/gen_exports.py (Windows DLL export/import macros).",
         "#if defined(_WIN32)", "#  define CAELESTIA_DLLEXPORT __declspec(dllexport)",
         "#  define CAELESTIA_DLLIMPORT __declspec(dllimport)", "#else",
         "#  define CAELESTIA_DLLEXPORT", "#  define CAELESTIA_DLLIMPORT", "#endif", ""]
for k in keys:
    lines += [f"#if defined(CAELESTIA_BUILD_{k})", f"#  define CAELESTIA_{k}_API CAELESTIA_DLLEXPORT",
              "#else", f"#  define CAELESTIA_{k}_API CAELESTIA_DLLIMPORT", "#endif", ""]
lines += ["// Macro-generated types use CAELESTIA_LOCAL_API; each header of a library sets it to that",
          "// library's own macro (push_macro/pop_macro), so expansion picks the owner library.",
          "#ifndef CAELESTIA_LOCAL_API", "#  define CAELESTIA_LOCAL_API", "#endif", ""]
(inc / "caelestia_export.h").write_text("\n".join(lines), encoding="utf-8")

# --- headers ---
DECL = re.compile(r"^(class|struct)(\s+)([A-Za-z_]\w*)(\s+final)?\s*(:|\{|$)")
# class/struct inside a (backslash-continued) #define body; names may contain ## pasting
MDECL = re.compile(r"^(\s*)(class|struct)(\s+)([A-Za-z_][\w#]*)(\s+final)?\s*(:|\{|\\|$)")
LOOSE = re.compile(r"\b(class|struct)\s+[A-Za-z_]")
total = 0
report = []
unmarked = []
macro_defs = []
watch = re.compile(r"ConfigSingleton|TokensSingleton|FontConfig|FontStyle")
watch_hits = []
for d, target in dir_to_target.items():
    key = lib_key(target)
    macro = f"CAELESTIA_{key}_API"
    local_begin = ('#pragma push_macro("CAELESTIA_LOCAL_API")\n#undef CAELESTIA_LOCAL_API\n'
                   f'#define CAELESTIA_LOCAL_API {macro}\n')
    local_end = '\n#pragma pop_macro("CAELESTIA_LOCAL_API")\n'
    for h in sorted(d.glob("*.hpp")) + sorted(d.glob("*.h")):
        text = h.read_text(encoding="utf-8", errors="replace")
        if "CAELESTIA_LOCAL_API" in text:
            continue
        lines = text.split("\n")
        out, changed, prev = [], 0, ""
        in_define, define_buf = False, []
        for ln, line in enumerate(lines, 1):
            stripped = line.rstrip("\r")
            if stripped.lstrip().startswith("#define"):
                in_define, define_buf = True, []
            new_line = line
            if in_define:
                m = MDECL.match(stripped)
                prev_in_define = define_buf[-1].lstrip() if define_buf else ""
                if m and "CAELESTIA_" not in stripped and "friend" not in stripped and not prev_in_define.startswith("template"):
                    # owner library is only known at the expansion site -> use the "local" macro
                    new_line = f"{m.group(1)}{m.group(2)}{m.group(3)}CAELESTIA_LOCAL_API {stripped[m.end(3):]}" + line[len(stripped):]
                    changed += 1
                define_buf.append(stripped)
            else:
                m = DECL.match(line)
                if m and macro not in line and not prev.lstrip().startswith("template"):
                    new_line = f"{m.group(1)}{m.group(2)}{macro} {line[m.end(2):]}"
                    changed += 1
                elif LOOSE.search(stripped) and macro not in stripped and not stripped.lstrip().startswith(("//", "friend", "enum", "template", "#")) and not stripped.rstrip().endswith(";"):
                    unmarked.append(f"{h.relative_to(root)}:{ln}: {stripped.strip()}")
            if watch.search(stripped) and len(watch_hits) < 120:
                watch_hits.append(f"{h.relative_to(root)}:{ln}: {stripped.strip()}")
            out.append(new_line)
            if in_define and not stripped.rstrip().endswith("\\"):
                if any(re.search(r"\b(class|struct)\b", b) for b in define_buf):
                    macro_defs.append(f"--- {h.relative_to(root)} (define ending line {ln}) ---\n" + "\n".join(define_buf))
                in_define = False
            if stripped.strip():
                prev = stripped
        body = "\n".join(out)
        inject = "#include <caelestia_export.h>\n" + local_begin
        if re.search(r"^#pragma once[ \t\r]*$", body, re.M):
            body = re.sub(r"^(#pragma once[ \t\r]*)$", lambda m_: m_.group(1) + "\n" + inject.rstrip("\n"), body, count=1, flags=re.M)
        else:
            body = inject + body
        body = body.rstrip("\n") + local_end
        h.write_text(body, encoding="utf-8")
        total += changed
        if changed:
            report.append(f"{h.relative_to(root)}: {changed} -> {macro} (macro-body types use CAELESTIA_LOCAL_API)")

# --- plugin/CMakeLists.txt ---
pc = plugin / "CMakeLists.txt"
t = pc.read_text(encoding="utf-8")
if "caelestia_export" not in t:
    t = re.sub(r"^(\s*add_subdirectory\()", 'include_directories("${CMAKE_CURRENT_SOURCE_DIR}/include")\n\\1', t, count=1, flags=re.M)
    t += '''
# --- Windows DLL export macros (added by tools/gen_exports.py) ---
if(WIN32)
    function(_caelestia_collect dir out)
        get_property(_t DIRECTORY "${dir}" PROPERTY BUILDSYSTEM_TARGETS)
        get_property(_s DIRECTORY "${dir}" PROPERTY SUBDIRECTORIES)
        foreach(_d IN LISTS _s)
            _caelestia_collect("${_d}" _sub)
            list(APPEND _t ${_sub})
        endforeach()
        set(${out} "${_t}" PARENT_SCOPE)
    endfunction()
    _caelestia_collect("${CMAKE_CURRENT_SOURCE_DIR}" _caelestia_all)
    foreach(_tgt IN LISTS _caelestia_all)
        if(_tgt MATCHES "^caelestia-(.+)$")
            get_target_property(_type ${_tgt} TYPE)
            if(_type STREQUAL "SHARED_LIBRARY")
                string(TOUPPER "${CMAKE_MATCH_1}" _n)
                string(REGEX REPLACE "[^A-Z0-9]" "_" _n "${_n}")
                target_compile_definitions(${_tgt} PRIVATE CAELESTIA_BUILD_${_n})
                message(STATUS "caelestia export: ${_tgt} -> CAELESTIA_BUILD_${_n}")
            endif()
        endif()
    endforeach()
endif()
'''
    pc.write_text(t, encoding="utf-8")

print("libraries:", ", ".join(f"{d.relative_to(src) if d != src else '.'}={t}" for d, t in sorted(dir_to_target.items(), key=lambda x: str(x[0]))))
print("\n".join(report))
print(f"marked {total} type definitions")
if len(sys.argv) > 2:
    rp = pathlib.Path(sys.argv[2])
    rp.parent.mkdir(parents=True, exist_ok=True)
    with rp.open("w", encoding="utf-8") as f:
        f.write("== marked ==\n" + "\n".join(report) + "\n\n")
        f.write("== class-like lines NOT marked (check these if link errors remain) ==\n" + "\n".join(unmarked[:400]) + "\n\n")
        f.write("== #define blocks that contain class/struct ==\n" + "\n\n".join(macro_defs[:60]) + "\n\n")
        f.write("== lines mentioning ConfigSingleton/TokensSingleton/FontConfig/FontStyle (first 120) ==\n" + "\n".join(watch_hits) + "\n")
